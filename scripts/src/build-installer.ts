/**
 * Builds the bootstrap contracts (contract/bootstrap, docs/decisions.md D-31, D-32) and writes
 * shared/src/installer-wasm.ts, which the setup page and the scripts read them from.
 *
 *   pnpm build:installer [--operator onanikes.near] [--check]
 *
 * 1. The installer, which installs one release only: the one whose SHA-256 is RELEASE_WASM_SHA256, copied
 *    from the store release-<its first 8 hex>.<operator>. Both are built into it.
 * 2. The factory, with everything it sets up built in from shared/ (factory/src/config.rs, written here): the
 *    installer's bytes, the role accounts' NEAR, allowances and methods, the contract's NEAR, USDC and the
 *    default limits. So a new release, operator, token or default needs a new build.
 * 3. The store.
 * The toolchain is pinned (contract/bootstrap/rust-toolchain.toml), so the same source builds the same bytes:
 * --check rebuilds and fails if they differ from the committed files.
 */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";

import { REPO_ROOT } from "@getleash/devkit/paths";
import {
  AGENT_METHODS,
  DEFAULT_POLICY,
  EXECUTOR_METHODS,
  FACTORY_RECORD,
  FT_STORAGE_DEPOSIT,
  HOSTED_ROLES,
  INSTALL_GAS,
  NETWORKS,
  REGISTRATION_GAS,
  RELEASE_WASM_BYTES,
  RELEASE_WASM_SHA256,
  releaseStoreId,
  sha256Hex,
  suggestedPolicyBalance,
  toBase64Url,
} from "@getleash/shared";

const { values } = parseArgs({
  options: { operator: { type: "string", default: "onanikes.near" }, check: { type: "boolean", default: false } },
});
const operator = values.operator!;
const store = releaseStoreId(operator);
const dir = join(REPO_ROOT, "contract/bootstrap");
const configPath = join(dir, "factory/src/config.rs");
const out = join(REPO_ROOT, "shared/src/installer-wasm.ts");
const token = NETWORKS.mainnet.usdc!;

// The flags come from contract/bootstrap/.cargo/config.toml only, whatever this shell has set.
const env: NodeJS.ProcessEnv = { ...process.env, GETLEASH_RELEASE_STORE: store, GETLEASH_RELEASE_SHA256: RELEASE_WASM_SHA256 };
for (const name of ["RUSTFLAGS", "CARGO_ENCODED_RUSTFLAGS", "CARGO_BUILD_RUSTFLAGS", "CARGO_TARGET_DIR"]) delete env[name];

function cargo(pkg: string) {
  const build = spawnSync("cargo", ["build", "--release", "--locked", "--target", "wasm32v1-none", "-p", pkg], { cwd: dir, env, stdio: "inherit" });
  if (build.status !== 0) {
    console.error(`✗ cargo build -p ${pkg} failed in contract/bootstrap (needs rustup; the toolchain and target install themselves)`);
    process.exit(1);
  }
}
const wasm = (name: string) => new Uint8Array(readFileSync(join(dir, "target/wasm32v1-none/release", `${name}.wasm`)));

cargo("getleash-installer");
const installer = wasm("getleash_installer");

/** What the factory sets up, from shared/, as Rust. `new` reads the limits exactly as initArgs writes them. */
const policyJson = JSON.stringify(DEFAULT_POLICY).slice(1, -1);
const config = `// Generated by \`pnpm build:installer\` (scripts/src/build-installer.ts) from shared/: do not edit.

/// The installer each contract starts with: sha256 ${sha256Hex(installer)}, ${installer.length} bytes.
pub const INSTALLER: &[u8] = &[${Array.from(installer).join(",")}];
/// The treasury token (Circle USDC on NEAR mainnet) and its decimals.
pub const TOKEN: &str = ${JSON.stringify(token)};
pub const TOKEN_DECIMALS: &str = "6";
/// GetLeash's default limits (DEFAULT_POLICY), as \`new\` reads them.
pub const POLICY_JSON: &str = ${JSON.stringify(policyJson)};
/// NEAR for each role account's gas, its key's gas allowance, and the methods the key may call.
pub const AGENT_BALANCE: u128 = ${HOSTED_ROLES.agent.balance};
pub const AGENT_ALLOWANCE: u128 = ${HOSTED_ROLES.agent.allowance};
pub const AGENT_METHODS: &str = ${JSON.stringify(AGENT_METHODS.join(","))};
pub const EXECUTOR_BALANCE: u128 = ${HOSTED_ROLES.executor.balance};
pub const EXECUTOR_ALLOWANCE: u128 = ${HOSTED_ROLES.executor.allowance};
pub const EXECUTOR_METHODS: &str = ${JSON.stringify(EXECUTOR_METHODS.join(","))};
/// NEAR for the contract: the release's storage plus 0.2 NEAR for its records.
pub const POLICY_BALANCE: u128 = ${suggestedPolicyBalance(RELEASE_WASM_BYTES)};
/// The contract's registration on the token, and the gas for it.
pub const REGISTRATION_DEPOSIT: u128 = ${FT_STORAGE_DEPOSIT};
pub const REGISTRATION_GAS: u64 = ${REGISTRATION_GAS};
/// What the factory keeps for its record of the name.
pub const RECORD: u128 = ${FACTORY_RECORD};
/// Gas for the installer's \`install\`.
pub const INSTALL_GAS: u64 = ${INSTALL_GAS};
`;

if (values.check) {
  if (readFileSync(configPath, "utf8") !== config) {
    console.error("✗ contract/bootstrap/factory/src/config.rs doesn't match shared/; run pnpm build:installer and review the change");
    process.exit(1);
  }
} else {
  writeFileSync(configPath, config);
}
cargo("getleash-factory");
cargo("getleash-store");
const factory = wasm("getleash_factory");
const storeCode = wasm("getleash_store");
const rustc = spawnSync("rustc", ["--version"], { cwd: dir, env, encoding: "utf8" }).stdout.trim();

const text = `// Generated by \`pnpm build:installer\` (scripts/src/build-installer.ts) from contract/bootstrap: do not edit.
// ${rustc}, wasm32v1-none.

/** The installer (D-31): it installs only the release with this SHA-256, copied from this store (both built in). */
export const INSTALLER_BUILD = {
  store: ${JSON.stringify(store)},
  release: ${JSON.stringify(RELEASE_WASM_SHA256)},
  sha256: ${JSON.stringify(sha256Hex(installer))},
  bytes: ${installer.length},
  wasm: ${JSON.stringify(toBase64Url(installer))},
} as const;

/** The factory (D-32): sets up a business's GetLeash from one call, with this installer and these values built in. */
export const FACTORY_BUILD = {
  token: ${JSON.stringify(token)},
  sha256: ${JSON.stringify(sha256Hex(factory))},
  bytes: ${factory.length},
  wasm: ${JSON.stringify(toBase64Url(factory))},
} as const;

/** The release store's code (D-31): \`set\` once by the operator, \`get\` for anyone. */
export const STORE_BUILD = {
  sha256: ${JSON.stringify(sha256Hex(storeCode))},
  bytes: ${storeCode.length},
  wasm: ${JSON.stringify(toBase64Url(storeCode))},
} as const;
`;

if (values.check) {
  if (readFileSync(out, "utf8") !== text) {
    console.error(`✗ shared/src/installer-wasm.ts doesn't match this build (${rustc}); run pnpm build:installer and review the change`);
    process.exit(1);
  }
  console.log("✓ contract/bootstrap/factory/src/config.rs and shared/src/installer-wasm.ts match the build");
} else {
  writeFileSync(out, text);
  console.log("✓ wrote contract/bootstrap/factory/src/config.rs and shared/src/installer-wasm.ts");
}
console.log(`  installer ${installer.length} bytes, sha256 ${sha256Hex(installer)}
    installs ${RELEASE_WASM_SHA256} from ${store}
  factory ${factory.length} bytes, sha256 ${sha256Hex(factory)}
  store ${storeCode.length} bytes, sha256 ${sha256Hex(storeCode)}`);
