/**
 * Builds the installer and the release store (contract/bootstrap, docs/decisions.md D-31) and writes
 * shared/src/installer-wasm.ts, which the setup page and the scripts read them from.
 *
 *   pnpm build:installer [--operator onanikes.near] [--check]
 *
 * The installer installs one release only: the one whose SHA-256 is RELEASE_WASM_SHA256, copied from the
 * store release-<its first 8 hex>.<operator>. Both are built into it, so a new release or another operator
 * needs a new build. The toolchain is pinned (contract/bootstrap/rust-toolchain.toml), so the same source
 * builds the same bytes: --check rebuilds and fails if they differ from the committed file.
 */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";

import { REPO_ROOT } from "@getleash/devkit/paths";
import { RELEASE_WASM_SHA256, releaseStoreId, sha256Hex, toBase64Url } from "@getleash/shared";

const { values } = parseArgs({
  options: { operator: { type: "string", default: "onanikes.near" }, check: { type: "boolean", default: false } },
});
const operator = values.operator!;
const store = releaseStoreId(operator);
const dir = join(REPO_ROOT, "contract/bootstrap");
const out = join(REPO_ROOT, "shared/src/installer-wasm.ts");

// The flags come from contract/bootstrap/.cargo/config.toml only, whatever this shell has set.
const env: NodeJS.ProcessEnv = { ...process.env, GETLEASH_RELEASE_STORE: store, GETLEASH_RELEASE_SHA256: RELEASE_WASM_SHA256 };
for (const name of ["RUSTFLAGS", "CARGO_ENCODED_RUSTFLAGS", "CARGO_BUILD_RUSTFLAGS", "CARGO_TARGET_DIR"]) delete env[name];

const build = spawnSync("cargo", ["build", "--release", "--locked", "--target", "wasm32v1-none"], { cwd: dir, env, stdio: "inherit" });
if (build.status !== 0) {
  console.error("✗ cargo build failed in contract/bootstrap (needs rustup; the toolchain and target install themselves)");
  process.exit(1);
}
const rustc = spawnSync("rustc", ["--version"], { cwd: dir, env, encoding: "utf8" }).stdout.trim();
const wasm = (name: string) => new Uint8Array(readFileSync(join(dir, "target/wasm32v1-none/release", `${name}.wasm`)));
const installer = wasm("getleash_installer");
const storeCode = wasm("getleash_store");

const text = `// Generated by \`pnpm build:installer\` (scripts/src/build-installer.ts) from contract/bootstrap: do not edit.
// ${rustc}, wasm32v1-none.

/** The installer (D-31): it installs only the release with this SHA-256, copied from this store (both built in). */
export const INSTALLER_BUILD = {
  store: ${JSON.stringify(store)},
  release: ${JSON.stringify(RELEASE_WASM_SHA256)},
  sha256: ${JSON.stringify(sha256Hex(installer))},
  bytes: ${installer.length},
  wasm: ${JSON.stringify(toBase64Url(installer))},
} as const;

/** The release store's code (D-31): \`set\` once by the operator, \`get\` for anyone. */
export const STORE_BUILD = {
  sha256: ${JSON.stringify(sha256Hex(storeCode))},
  bytes: ${storeCode.length},
  wasm: ${JSON.stringify(toBase64Url(storeCode))},
} as const;
`;

if (values.check) {
  if (readFileSync(out, "utf8") !== text) {
    console.error(`✗ shared/src/installer-wasm.ts doesn't match this build (${rustc}); run pnpm build:installer and review the change`);
    process.exit(1);
  }
  console.log("✓ shared/src/installer-wasm.ts matches the build");
} else {
  writeFileSync(out, text);
  console.log(`✓ wrote shared/src/installer-wasm.ts`);
}
console.log(`  installer ${installer.length} bytes, sha256 ${sha256Hex(installer)}
    installs ${RELEASE_WASM_SHA256} from ${store}
  store ${storeCode.length} bytes, sha256 ${sha256Hex(storeCode)}`);
